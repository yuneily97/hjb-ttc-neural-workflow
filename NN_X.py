class OVM_PINN_Trainer:
    def __init__(self, model, alpha, beta, initial_lr=0.001, patience=50, batch_size=64):
        self.model = model
        self.alpha = alpha
        self.beta = beta
        self.batch_size = batch_size
        self.optimizer = keras.optimizers.Adam(learning_rate=initial_lr)
        self.best_loss = float('inf')
        self.wait = 0
        self.patience = patience

    def sample_batch(self):
        """
        Returns a random batch with multiple time steps per sample.
        For each sample, 100 time instants (including t=0 and t=1) are generated.
        """
        idx = np.random.choice(num_samples, self.batch_size, replace=False)
        
                                                                                                  
        t_batch = []
        for _ in range(self.batch_size):
                                                            
            t_rand = np.random.uniform(0, 1, size=(num_timesteps - 2))
                                    
            t_all = np.concatenate(([0.0], t_rand, [1.0]))
                                   
            t_batch.append(t_all)
        t_batch = np.array(t_batch, dtype=np.float32)                                      
        t_batch = t_batch[..., None]                                         
        
                                                                                          
        nearest_time_idx = np.round(t_batch * (len(time_points)-1)).astype(int).squeeze(-1)                                      
        
                                                                         
        X0_batch = tf.gather(X0_all, idx)
        V0_batch = tf.gather(V0_all, idx)
        v_l_batch = tf.gather(v_l_all, idx)
        ttc_batch = tf.gather(ttc_all, idx)
        
                                                                                                                
        X0_batch_rep = tf.repeat(tf.expand_dims(X0_batch, axis=1), repeats=num_timesteps, axis=1)
        V0_batch_rep = tf.repeat(tf.expand_dims(V0_batch, axis=1), repeats=num_timesteps, axis=1)
        v_l_batch_rep = tf.repeat(tf.expand_dims(v_l_batch, axis=1), repeats=num_timesteps, axis=1)
        ttc_batch_rep = tf.repeat(tf.expand_dims(ttc_batch, axis=1), repeats=num_timesteps, axis=1)
        
                                                                                                                        
        X_ref = []
        V_ref = []
        for i in range(self.batch_size):
            x_sample = []
            v_sample = []
            for j in range(num_timesteps):
                idx_time = nearest_time_idx[i, j]
                x_sample.append(X_full_np[idx[i], idx_time])
                v_sample.append(V_full_np[idx[i], idx_time])
            X_ref.append(x_sample)
            V_ref.append(v_sample)
        X_ref = tf.constant(X_ref, dtype=tf.float32)[..., None]                                         
        V_ref = tf.constant(V_ref, dtype=tf.float32)[..., None]                                         
        
        return X0_batch_rep, V0_batch_rep, v_l_batch_rep,ttc_batch_rep, tf.constant(t_batch, dtype=tf.float32), X_ref, V_ref


  
                                                                                                                     
                                                                                                                   
                                                        
                                           
                                           
                                                                               
                          
                                           
                                                                               
                          
                                            
                                            
                                                                        
                                                     
                                                       
                             
                               
                                   
                                                                   
                                                                          
                                          
                                                                           
                                                                         
        
                                                                                       
                                                                 
                                                                 
                                                         
                                             
                                             
                                                                                           
                          
                                             
                                                                                           
                          
                                               

                                                     
                                                                                           
                                                                               
                                                                                              
                                                                                              
                                                                        

                                                     
                                                                                
                                                                        
        
                                                      
                                                     
                                                       
                                                   

                                                                        
                                                                                  
                                                                                  
                                                                                   
                                                                               

                                                           
                                                                               

                                                                                              
                                                  
                                                 
                                                   
                                                 

                                                                                                                        

                                                                                      
                                                                                        
        
                                                                         
    

    @tf.function
    def loss_fn(self, X0, V0, v_l, ttc, t_in, X_ref, V_ref):
        """
        Compute the combined loss over all sampled time instants.
        The inputs X0, V0, v_l, t_in (and reference data) have shape (batch_size, num_timesteps, 1).
        """
        batch_size = tf.shape(X0)[0]
        num_t = tf.shape(X0)[1]
        
                                                                                                              
        X0_flat = tf.reshape(X0, [batch_size * num_t, 1])
        V0_flat = tf.reshape(V0, [batch_size * num_t, 1])
        v_l_flat = tf.reshape(v_l, [batch_size * num_t, 1])
        t_in_flat = tf.reshape(t_in, [batch_size * num_t, 1])
        ttc_flat = tf.reshape(ttc, [batch_size * num_t, 1])

        with tf.GradientTape(persistent=True) as tape:
            tape.watch(t_in_flat)
            inputs = tf.concat([X0_flat, V0_flat, v_l_flat, ttc_flat, t_in_flat], axis=-1)                                
            X_pred = self.model(inputs)                                
        
                                                
        dX_dt_pred = tape.gradient(X_pred, t_in_flat)
        del tape

                                                                 
        first_NN_out = reconstructed_model(inputs)
        first_NN_out_V = first_NN_out[:, 1:2]

                                                                                
        pde_res_x = dX_dt_pred - first_NN_out_V
        pde_loss = tf.reduce_sum(tf.square(pde_res_x))
        
                                           
        X0_bc = X0[:, 0, :]                          
        V0_bc = V0[:, 0, :]
        v_l_bc = v_l[:, 0, :]
        t0 = tf.zeros_like(X0_bc)
        ttc_bc = ttc[:, 0, :]                                    
        inputs0 = tf.concat([X0_bc, V0_bc, v_l_bc, ttc_bc, t0], axis=-1)
        
        X_pred_bc = self.model(inputs0)
        bc_loss = tf.reduce_sum(tf.square(X_pred_bc - X0_bc))
        

        eps = 0.000001
        lambda_ic = 2                                           

        def band_penalty(err):
                                                  
            p = tf.abs(err - eps) + tf.abs(err + eps) - 50.0*eps
            return tf.maximum(p, 0.0)

        pen_x = band_penalty(X_pred_bc - X0_bc)

        bc_loss = tf.reduce_mean(tf.square(pen_x))

        
        total_loss = 2* pde_loss + bc_loss * 50000
        return total_loss, pde_loss, bc_loss, X_pred

    @staticmethod
    def r2_score(y_true, y_pred):
        ss_res = tf.reduce_sum(tf.square(y_true - y_pred))
        ss_tot = tf.reduce_sum(tf.square(y_true - tf.reduce_mean(y_true)))
        return 1.0 - ss_res / (ss_tot + 1e-10)

    def train_step(self):
        """
        Sample a batch with multiple time steps per sample, compute the loss,
        update the network weights, and compute R^2 scores over all sampled times.
        """
        X0_b, V0_b, v_l_b, ttc_b, t_b, X_ref_b, V_ref_b = self.sample_batch()

        with tf.GradientTape() as tape:
            total_loss, pde_loss, bc_loss, X_pred_flat = \
                self.loss_fn(X0_b, V0_b, v_l_b, ttc_b, t_b, X_ref_b, V_ref_b)
        
        grads = tape.gradient(total_loss, self.model.trainable_variables)
        self.optimizer.apply_gradients(zip(grads, self.model.trainable_variables))

                                                                               
        batch_size = tf.shape(X0_b)[0]
        num_t = tf.shape(X0_b)[1]
        X_ref_flat = tf.reshape(X_ref_b, [batch_size * num_t, 1])

        r2_x = self.r2_score(X_ref_flat, X_pred_flat)

                                                                      
        cur_loss = total_loss.numpy()
        if cur_loss < self.best_loss:
            self.best_loss = cur_loss
            self.wait = 0
        else:
            self.wait += 1
        if self.wait >= self.patience:
            old_lr = self.optimizer.learning_rate.numpy()
            new_lr = max(old_lr * 0.75, 1e-20)
            self.optimizer.learning_rate.assign(new_lr)
            self.wait = 0
            print(f"🔹 Learning rate reduced from {old_lr:.2e} to {new_lr:.2e}.")

        return total_loss, r2_x
    
                                                       
                   
                                                       

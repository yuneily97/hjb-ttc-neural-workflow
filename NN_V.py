    @staticmethod
    def a_front_tf(t):
        return 3.5 * tf.exp(-tf.math.log(100.0) * t) * tf.sin(8.0 * np.pi * t)

    @tf.function
    def loss_fn(self, X0, V0, v_l, ttc, t_in, X_ref, V_ref):
        """
        Compute the combined loss over all sampled time instants.
        The inputs X0, V0, v_l, t_in (and reference data) have shape (batch_size, num_timesteps, 1).
        """
        batch_size = tf.shape(X0)[0]
        num_t = tf.shape(X0)[1]
        
                                                                                                              
        X0_flat = tf.reshape(X0, [batch_size * num_t, 1])
        V0_flat = tf.reshape(V0, [batch_size * num_t, 1])
        v_l_flat = tf.reshape(v_l, [batch_size * num_t, 1])
        t_in_flat = tf.reshape(t_in, [batch_size * num_t, 1])
        ttc_flat = tf.reshape(ttc, [batch_size * num_t, 1])

        with tf.GradientTape(persistent=True) as tape:
            tape.watch(t_in_flat)
            inputs = tf.concat([X0_flat, V0_flat, v_l_flat, ttc_flat, t_in_flat], axis=-1)                                
            X_V_pred = self.model(inputs)                                
            X_pred = X_V_pred[:, 0:1]
                                                                    
            V_pred = X_V_pred[:, 1:2]
        
        dX_dt_pred = tape.gradient(X_pred, t_in_flat)
        dV_dt_pred = tape.gradient(V_pred, t_in_flat)
        del tape

                                   
        v_opt = tf.tanh(X_pred - 2.0) + tf.tanh(2.0)
        pde_res_x = dX_dt_pred - V_pred

                                                                                                                               
                                                            
                                                            

                                            
                                     
                                            
                                 
                                   
                                 
                                          
                                               
                                                             
                                                                                                          
                                                             
        
                                                                                    
                                  
                                                                   

                                                                        
                                                                                                            
                                                                            

                                            
                                                                                                           
                                                                                 

                                                   
                                                      
                                                                                                                                 
        
                                                                                                                                 
                                     
        a_front_val = self.a_front_tf(t_in_flat)                                  

                                                         
        v_l_flat_const = tf.reshape(v_l, [batch_size * num_t, 1])

        t_idx = tf.cast(tf.round(t_in_flat * (len(time_points) - 1)), tf.int32)
        t_idx = tf.clip_by_value(t_idx, 0, len(time_points) - 1)

        delta_v_selected = tf.gather(delta_v_lead_tf, tf.squeeze(t_idx, axis=1))
        delta_v_selected = tf.reshape(delta_v_selected, [-1, 1])

        v_l_flat = v_l_flat_const + delta_v_selected

                                                
                                 
                                           
                                                                                    
                                       
        lam_hjb = tf.minimum(V_pred, 0.0)

        hjb_inputs = tf.concat(
            [t_in_flat, X_pred, lam_hjb, v_l_flat],
            axis=1
        )

                                                                           
                                                                                      
        hjb_inputs_sg = tf.stop_gradient(hjb_inputs)

        hjb_ttc_output = nn_model(hjb_inputs_sg, training=False)
        hjb_ttc = tf.reshape(hjb_ttc_output[:, 0], (-1, 1))

                                                                  
        hjb_ttc = tf.stop_gradient(hjb_ttc)


        remaining_horizon = tf.maximum(T - t_in_flat, 0.0)
        no_collision_hjb = hjb_ttc >= remaining_horizon - 1e-4

        ttc_col = tf.where(
            tf.logical_or(V_pred >= 0.0, no_collision_hjb),
            T * tf.ones_like(hjb_ttc),
            hjb_ttc,
        )

        ttc_col = tf.clip_by_value(ttc_col, 1e-4, T)
                                                                                                           

        pde_res_v = dV_dt_pred - (
            a_front_val
            - self.alpha * (v_opt - v_l_flat + V_pred)
            - self.beta * V_pred / (ttc_col / T)**2
        )

                                                                                                                  
        mask_pde = tf.cast(ttc_col >= 0.5, tf.float32)
        num_pde = tf.reduce_sum(mask_pde)
        pde_loss_x = tf.cond(num_pde > 0,
            lambda: tf.reduce_sum(tf.square(pde_res_x) * mask_pde) / num_pde,
            lambda: 0.0)
        pde_loss_v = tf.cond(num_pde > 0,
            lambda: tf.reduce_sum(tf.square(pde_res_v) * mask_pde) / num_pde,
            lambda: 0.0)
        pde_loss = pde_loss_x + pde_loss_v
                                          
                                                                      
                                                   
        X0_bc = X0[:, 0, :]                          
        V0_bc = V0[:, 0, :]
        v_l_bc = v_l[:, 0, :]
        t0 = tf.zeros_like(X0_bc)
        ttc_bc = ttc[:, 0, :]                                    
        inputs0 = tf.concat([X0_bc, V0_bc, v_l_bc, ttc_bc, t0], axis=-1)
        X_V_pred_0 = self.model(inputs0)
        bc_loss = tf.reduce_mean(tf.square(X_V_pred_0[:, 0:1] - X0_bc)) \
                + tf.reduce_mean(tf.square(X_V_pred_0[:, 1:2] - V0_bc))
        
        eps = 0.0001
        lambda_ic = 2                                           

        def band_penalty(err):
                                                  
            p = tf.abs(err - eps) + tf.abs(err + eps) - 2.0*eps
            return tf.maximum(p, 0.0)

        pen_x = band_penalty(X_V_pred_0[:, 0:1] - X0_bc)
        pen_v = band_penalty(X_V_pred_0[:, 1:2] - V0_bc)

        bc_loss = tf.reduce_mean(tf.square(pen_x))+tf.reduce_mean(tf.square(pen_v))
                                                      
                                                                                     
                                                                 

                                                                                     
        X_ref_flat = tf.reshape(X_ref, [batch_size * num_t, 1])
        V_ref_flat = tf.reshape(V_ref, [batch_size * num_t, 1])
        mask_data = tf.cast(ttc_col <= 0.7, tf.float32)
        num_data = tf.reduce_sum(mask_data)
        data_loss_x = tf.cond(num_data > 0,
            lambda: tf.reduce_sum(tf.square(X_pred - X_ref_flat) * mask_data) / num_data,
            lambda: 0.0)
        data_loss_v = tf.cond(num_data > 0,
            lambda: tf.reduce_sum(tf.square(V_pred - V_ref_flat) * mask_data) / num_data,
            lambda: 0.0)
        data_loss = data_loss_x + data_loss_v

        def total_variation_penalty(y_pred_tensor):
                                                                                         
            y_pred_tensor = tf.reshape(y_pred_tensor, [batch_size, num_t, 2])
            position_diff_sq = tf.square(y_pred_tensor[:, 1:, 0] - y_pred_tensor[:, :-1, 0])
            velocity_diff_sq = tf.square(y_pred_tensor[:, 1:, 1] - y_pred_tensor[:, :-1, 1])
            return tf.reduce_mean(position_diff_sq + velocity_diff_sq)

                                                   
        tv_loss = total_variation_penalty(tf.concat([X_pred, V_pred], axis=1))
                                                                      
        
        pde_mean  = tf.reduce_mean(tf.abs(pde_loss))
        bc_mean   = tf.reduce_mean(tf.abs(bc_loss))
        data_mean = tf.reduce_mean(tf.abs(data_loss))
        tv_mean = tf.reduce_mean(tf.abs(tv_loss))

                                                                      
        pde_exp  = tf.floor(tf.math.log(pde_mean + epsilon) / tf.math.log(10.0))
        bc_exp   = tf.floor(tf.math.log(bc_mean + epsilon)  / tf.math.log(10.0))
        data_exp = tf.floor(tf.math.log(data_mean + epsilon) / tf.math.log(10.0))
        tv_exp = tf.floor(tf.math.log(tv_mean + epsilon) / tf.math.log(10.0))

                                                         
        max_exp = tf.reduce_max(tf.stack([pde_exp, bc_exp, data_exp,tv_exp]))

                                                                                            
        scale_pde  = 10.0 ** (max_exp - pde_exp)
        scale_bc   = 10.0 ** (max_exp - bc_exp)
        scale_data = 10.0 ** (max_exp - data_exp)
        scale_tv = 10.0 ** (max_exp - tv_exp-2)

                                                                                                                      

                                                                                    
        total_loss = 6*pde_loss + 75*bc_loss + 10*data_loss                                                                                                                            
        
        return total_loss, pde_loss, bc_loss, data_loss, X_pred, V_pred

    @staticmethod
    def r2_score(y_true, y_pred):
        """
        Compute R^2 = 1 - SS_res / SS_tot.
        Both y_true and y_pred should be flattened.
        """
        ss_res = tf.reduce_sum(tf.square(y_true - y_pred))
        ss_tot = tf.reduce_sum(tf.square(y_true - tf.reduce_mean(y_true)))
        return 1.0 - ss_res / (ss_tot + 1e-10)

    def train_step(self):
        """
        Sample a batch with multiple time steps per sample, compute the loss,
        update the network weights, and compute R^2 scores over all sampled times.
        """
        X0_b, V0_b, v_l_b, ttc_b, t_b, X_ref_b, V_ref_b = self.sample_batch()

        with tf.GradientTape() as tape:
            total_loss, pde_loss, bc_loss, data_loss, X_pred_flat, V_pred_flat = \
                self.loss_fn(X0_b, V0_b, v_l_b, ttc_b, t_b, X_ref_b, V_ref_b)
        
        grads = tape.gradient(total_loss, self.model.trainable_variables)
        self.optimizer.apply_gradients(zip(grads, self.model.trainable_variables))

                                                                               
        batch_size = tf.shape(X0_b)[0]
        num_t = tf.shape(X0_b)[1]
        X_ref_flat = tf.reshape(X_ref_b, [batch_size * num_t, 1])
        V_ref_flat = tf.reshape(V_ref_b, [batch_size * num_t, 1])

        r2_x = self.r2_score(X_ref_flat, X_pred_flat)
        r2_v = self.r2_score(V_ref_flat, V_pred_flat)

                                                                      
        cur_loss = total_loss.numpy()
        if cur_loss < self.best_loss:
            self.best_loss = cur_loss
            self.wait = 0
        else:
            self.wait += 1
        if self.wait >= self.patience:
            old_lr = self.optimizer.learning_rate.numpy()
            new_lr = max(old_lr * 0.75, 1e-20)
            self.optimizer.learning_rate.assign(new_lr)
            self.wait = 0
            print(f"🔹 Learning rate reduced from {old_lr:.2e} to {new_lr:.2e}.")

        return total_loss, r2_x, r2_v

                                                       
                   
                                                       

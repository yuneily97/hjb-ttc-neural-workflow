def ovm_dynamics(y, t, t_initial, v_lead_profile, alpha_val=2):
    """
    Ground-truth OVM Dynamics:
      X' = V
      V' = -alpha*(v_opt - v_lead + V)
    where v_opt = tanh(X-2) + tanh(2)
    """
    X, V = y
                                           

    v_opt = np.tanh(X - 2) + np.tanh(2)
    dX_dt = V

    dV_dt = a_front(t_initial+t)-alpha_val * (v_opt - v_lead_profile[int((t_initial+t) / dt)] + V)
                                                             
    return [dX_dt, dV_dt]

def proposed_dynamics(t, y, alpha_val, beta_val, v_lead_profile):
    """
    Dynamics used for the ground truth trajectory:
      X' = V
      V' = -alpha*(v_opt - v_lead + V) - beta * V/((ttc/T)**2 + eps)
    Here, ttc is computed via simulation when V < 0.
    """
    X, V = y
    v_opt = np.tanh(X - 2) + np.tanh(2)
    dX_dt = V
    ttc = T
    
    t_array = np.arange(0, T, dt)
    if V < 0:
                                                                                   
                                                                                                        
        sol = odeint(ovm_dynamics, [X, V], t_array, args=(t,v_lead_profile))
        X_trajectory = sol[:, 0]
        if len(np.where(X_trajectory <= 0)[0]) != 0:
            ttc = t_array[np.where(X_trajectory <= 0)[0][0]]
            if ttc > T: 
                ttc = T
    eps = 1e-6
    dV_dt = a_front(t)-alpha_val * (v_opt - v_lead_profile[int(t/dt)] + V) - beta_val * V / ((ttc/T)**2 + eps)
    return [dX_dt, dV_dt]

                                                              

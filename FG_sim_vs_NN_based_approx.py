def a_front(t):
    if t <= T:
        return 3.5 * np.exp(-np.log(100) * t) * np.sin(8 * np.pi * t)
    else:
        return 0.0


def a_front_np(t):
    return 3.5 * np.exp(-np.log(100) * t) * np.sin(8 * np.pi * t)


time_points_OVM = np.arange(0, T + dt, dt)

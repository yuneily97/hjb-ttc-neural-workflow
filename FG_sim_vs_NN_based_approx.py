    """
    Input:
        [X0, V0, v_lead, ttc0, t]
    Output:
        X_pred(t)
    """
    def __init__(self):
        super(PINN_OVM, self).__init__()
        self.hidden_layer1 = Dense(256, activation="tanh")
        self.hidden_layer2 = Dense(256, activation="swish")
        self.hidden_layer3 = Dense(256, activation="tanh")
        self.hidden_layer4 = Dense(256, activation="swish")
        self.hidden_layer5 = Dense(256, activation="tanh")
        self.hidden_layer6 = Dense(256, activation="swish")
        self.output_layer = Dense(1, activation=None)

    def call(self, inputs):
        x = self.hidden_layer1(inputs)
        x = self.hidden_layer2(x)
        x = self.hidden_layer3(x)
        x = self.hidden_layer4(x)
        x = self.hidden_layer5(x)
        x = self.hidden_layer6(x)
        out = self.output_layer(x)
        return out



def predict_ttc_from_new_model(X_arr, V_arr, vlead_arr, T_hor=1.0):
    """
    Predict TTC using the new 4-input model:
        [s, Delta x, lambda, v_leader] = [0, X, V, v_lead]

    Rules:
    - default TTC = T_hor
    - if X <= 0, TTC = 0
    - if V >= 0, TTC = T_hor
    - only query NN when X > 0 and V < 0
    """
    X_arr = np.asarray(X_arr, dtype=np.float32).reshape(-1)
    V_arr = np.asarray(V_arr, dtype=np.float32).reshape(-1)
    vlead_arr = np.asarray(vlead_arr, dtype=np.float32).reshape(-1)

    n = len(X_arr)
    ttc_out = np.full(n, T_hor, dtype=np.float32)

                                          
    bad_x = X_arr <= 0
    ttc_out[bad_x] = 0.0

                                                 
    mask = (X_arr > 0) & (V_arr < 0)

    if np.any(mask):
        X_use = X_arr[mask].copy()
        V_use = V_arr[mask].copy()
        vl_use = vlead_arr[mask].copy()

                                                      
        X_use = np.clip(X_use, 0.0, 1.5)
        V_use = np.clip(V_use, -V_MAX, 0.0)

        feasible_vl_hi = np.maximum(0.0, V_MAX + V_use)
        vl_use = np.clip(vl_use, 0.0, feasible_vl_hi)

        s_use = np.zeros_like(X_use, dtype=np.float32)

        nn_inputs = np.stack([s_use, X_use, V_use, vl_use], axis=1).astype(np.float32)
        pred = ttc_model.predict(nn_inputs, verbose=0).reshape(-1)

        pred = np.clip(pred, 0.0, T_hor)
        ttc_out[mask] = pred.astype(np.float32)

    return ttc_out.reshape(-1, 1)


                                                       
                                                      
                                                       
class SineLayer(Layer):
    def __init__(self, units, omega_0=30):
        super().__init__()
        self.units = units
        self.omega_0 = omega_0
        self.linear = Dense(units, use_bias=True)

    def call(self, x):
        return tf.sin(self.omega_0 * self.linear(x))


class PINN_OVM1(tf.keras.Model):
    """
    Input:
        [X0, V0, v_lead, ttc0, t]
    Output:
        [X_pred(t), V_pred(t)]
    """
    def __init__(self):
        super(PINN_OVM1, self).__init__()
        self.hidden_layer1 = Dense(256)
        self.act2 = LeakyReLU(alpha=0.001)
        self.hidden_layer2 = Dense(128, activation="tanh")
        self.sine2 = SineLayer(256, omega_0=10)
        self.hidden_layer4 = Dense(128, activation="swish")
        self.hidden_layer5 = Dense(128, activation="tanh")
        self.hidden_layer6 = Dense(128, activation="swish")
        self.output_layer = Dense(2, activation=None)

    def call(self, inputs):
        x = self.hidden_layer1(inputs)
        x = self.act2(x)
        x = self.hidden_layer2(x)
        x = self.sine2(x)
        x = self.hidden_layer4(x)
        x = self.hidden_layer5(x)
        x = self.hidden_layer6(x)
        out = self.output_layer(x)

        X_pred = tf.nn.softplus(out[:, 0:1])
        V_pred = out[:, 1:2]
        return tf.concat([X_pred, V_pred], axis=-1)



delta_v_lead2 = delta_v_lead[-1] * np.ones_like(np.arange(0, 4 * T + dt, dt))
delta_v_lead = np.concatenate([delta_v_lead, delta_v_lead2])


def ovm_dynamics(y, t, t_initial, v_lead_profile, alpha_val=2):
    X, V = y
    v_opt = np.tanh(X - 2) + np.tanh(2)
    dX_dt = V
    idx = min(int((t_initial + t) / dt), len(v_lead_profile) - 1)
    dV_dt = a_front(t_initial + t) - alpha_val * (v_opt - v_lead_profile[idx] + V)
    return [dX_dt, dV_dt]


def proposed_dynamics(t, y, alpha_val, beta_val, v_lead_profile):
    """
    Ground-truth simulation using numerical TTC.
    """
    X, V = y
    v_opt = np.tanh(X - 2) + np.tanh(2)
    dX_dt = V
    ttc = T

    t_array = np.arange(0, T, dt)
    if V < 0:
        sol = odeint(ovm_dynamics, [X, V], t_array, args=(t, v_lead_profile))
        X_trajectory = sol[:, 0]
        hit_idx = np.where(X_trajectory <= 0)[0]
        if len(hit_idx) != 0:
            ttc = t_array[hit_idx[0]]
            if ttc > T:
                ttc = T

    eps = 1e-6
    idx = min(int(t / dt), len(v_lead_profile) - 1)
    dV_dt = a_front(t) - alpha_val * (v_opt - v_lead_profile[idx] + V) - beta_val * V / ((ttc / T) ** 2 + eps)
    return [dX_dt, dV_dt]


                                                       
                                     
                                                       

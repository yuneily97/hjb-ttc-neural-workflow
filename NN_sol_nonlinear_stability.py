class PINN_OVM1(tf.keras.Model):
    """
    A feedforward network that takes in:
       [X(0), V(0), v_lead, t]
    and outputs:
       [X_pred(t), V_pred(t)].
    """
    def __init__(self):
        super(PINN_OVM1, self).__init__()
                                        
                                                             
                                                           
                                                             
                                                                                                                     
                                                            
                                                            
                                                                        
        self.hidden_layer1 = Dense(256)
        self.act2 = LeakyReLU(alpha= 0.001)                                 
        self.hidden_layer2 = Dense(128, activation="tanh")
        self.sine2         = SineLayer(256, omega_0=10)                                                                
        self.hidden_layer4 = Dense(128, activation="swish")
                                         
                                                                            
        self.hidden_layer5 = Dense(128, activation="tanh")
        self.hidden_layer6 = Dense(128, activation="swish")
        self.output_layer  = Dense(2, activation=None)                

    def call(self, inputs):
        """
        inputs shape: (batch_size, 4) -> [X0, V0, v_lead, t]
        """
                                        
                           
                                   
                           
                                   
                                   
                                   
                                                              
                                                                                  
                                              
                              
                                                     
                                      
        x = self.hidden_layer1(inputs)
        x = self.act2(x) 
        x = self.hidden_layer2(x)
        x = self.sine2(x)
        x = self.hidden_layer4(x)
                                   
                           
        x = self.hidden_layer5(x)
        x = self.hidden_layer6(x)
        out = self.output_layer(x)                          
                                                                                
        X_pred = tf.nn.softplus(out[:, 0:1])
        V_pred = out[:, 1:2]
        return tf.concat([X_pred, V_pred], axis=-1)


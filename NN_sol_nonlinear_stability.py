class SineLayer(Layer):
    def __init__(self, units, omega_0=30):
        super().__init__()
        self.units = units
        self.omega_0 = omega_0
        self.linear = Dense(units, use_bias=True)

    def call(self, x):
        return tf.sin(self.omega_0 * self.linear(x))


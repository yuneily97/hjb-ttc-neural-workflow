alpha = 2.0                                   
beta = 3.0
T = 1.0                         
dt = 0.01                                          
time_points = np.arange(0, T + dt, dt)
epsilon = 0

samples_X0 = []
samples_vl = []
samples_v0 = []

                           
samples_X0.append(np.array([0.12]))
samples_vl.append(np.array([0.1]))

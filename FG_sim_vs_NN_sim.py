def a_front(t):
    return 3.5 * np.exp(-np.log(100) * t) * np.sin(8 * np.pi * t)


def ovm_dynamics(y, t, t_initial, alpha_val=2):
    """
    Ground-truth OVM Dynamics:
      X' = V
      V' = -alpha*(v_opt - v_lead + V) + a_front(t_initial+t)
      v_lead' = a_front(t_initial+t)
    """
    X, V, v_lead = y
    v_opt = np.tanh(X - 2) + np.tanh(2)

    dX_dt = V
    dV_dt = - alpha_val * (v_opt - v_lead + V)                                                           
    dv_lead_dt = 0                       

    return [dX_dt, dV_dt, dv_lead_dt]


def proposed_dynamics(t, y, alpha_val, beta_val, v_lead):
    """
    Dynamics used for the ground-truth trajectory:
      X' = V
      V' = -alpha*(v_opt - v_lead(t) + V) - beta * V/((ttc/T)^2 + eps) + a_front(t)

    Here, TTC is computed by numerical simulation when V < 0.
    """
    X, V = y
    v_opt = np.tanh(X - 2) + np.tanh(2)
    dX_dt = V
    ttc = T

    a_lead = a_front(time_points)
    delta_v_lead = cumtrapz(a_lead, time_points, initial=0)
    v_lead_profile = v_lead + delta_v_lead

    idx = min(int(t / dt), len(v_lead_profile) - 1)
    t_array = np.arange(0, T, dt)

    if V < 0:
        sol = odeint(ovm_dynamics, [X, V, v_lead_profile[idx]], t_array, args=(t,))
        X_trajectory = sol[:, 0]

        hit_indices = np.where(X_trajectory <= 0)[0]
        if len(hit_indices) != 0:
            ttc = t_array[hit_indices[0]]
            if ttc > T:
                ttc = T

    eps = 1e-6
    dV_dt = (
        a_front(t)
        - alpha_val * (v_opt - v_lead_profile[idx] + V)
        - beta_val * V / ((ttc / T) ** 2 + eps)
    )
    return [dX_dt, dV_dt]


def proposed_dynamics_NN(t, y, alpha_val, beta_val, v_lead):
    """
    Dynamics using the NN-predicted TTC.

    Per your requested mapping:
        s = 0
        Delta x = X
        lambda = V
        v_leader = v_lead

    So the NN input is:
        [0, X, V, v_lead]
    """
    X, V = y
    v_opt = np.tanh(X - 2) + np.tanh(2)
    dX_dt = V
    ttc = T

                                                                                    
    a_lead = a_front(time_points)
    delta_v_lead = cumtrapz(a_lead, time_points, initial=0)
    v_lead_profile = v_lead + delta_v_lead

    idx = min(int(t / dt), len(v_lead_profile) - 1)

    if V < 0:
                                          
                                                           
        X_test_sample = np.array([[0.0, X, V, v_lead_profile[int(t/dt)]]], dtype=np.float32)

        y_pred_sample = nn_model.predict(X_test_sample, verbose=0)
        ttc = float(y_pred_sample[0, 0])

                                      
        ttc = np.clip(ttc, 0.0, T)

    eps = 1e-6
    dV_dt = (
        a_front(t)
        - alpha_val * (v_opt - v_lead_profile[idx] + V)
        - beta_val * V / ((ttc / T) ** 2 + eps)
    )
    return [dX_dt, dV_dt]


                                                       
                                                                 
                                                       
                           
X_full_gt = []
V_full_gt = []

for i in range(num_samples):
    y0 = [X0_all_np[i], V0_all_np[i]]
    sol = solve_ivp(
        proposed_dynamics,
        [0, T],
        y0,
        t_eval=time_points,
        args=(alpha, beta, v_l_all_np[i]),
        method='RK45'
    )
    X_full_gt.append(sol.y[0])
    V_full_gt.append(sol.y[1])

X_full_gt = np.array(X_full_gt, dtype=np.float32)
V_full_gt = np.array(V_full_gt, dtype=np.float32)
print("Computed ground-truth trajectories.")

                       
X_full_nn = []
V_full_nn = []


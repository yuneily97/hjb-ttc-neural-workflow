TANH2 = np.tanh(2.0)
V_MAX = 1.0 + TANH2

XI_MIN = 0.0
XI_MAX = 1.5

LAM_MIN = -V_MAX
LAM_MAX = 0.0

VL_MIN = 0.0
VL_MAX = V_MAX


                                                              
                 
                                   
                                                              
def optimal_velocity(delta_x):
    return np.tanh(delta_x - 2.0) + TANH2


def effective_dt(T_hor, dt_ratio=0.001, dt_abs_max=None):
    dt = float(dt_ratio) * float(T_hor)
    if dt_abs_max is not None:
        dt = min(dt, float(dt_abs_max))
    return max(dt, 1e-6)


def leader_acceleration(t):
    t = np.asarray(t, dtype=np.float64)
    active = (t >= 0.0) & (t <= 1.0)
    return np.where(active, 3.5 * np.exp(-np.log(100.0) * t) * np.sin(8.0 * np.pi * t), 0.0)


def compute_ground_truth_ovm(X, T_hor=1.0, alpha=2.0, dt_ratio=0.001, dt_abs_max=None):
    """
    X: [N, 4] with columns [s, Δx, λ, v_leader]
    Returns dynamic-based TTC clipped by remaining horizon.
    """
    X = np.asarray(X, dtype=np.float64)
    out = np.zeros(len(X), dtype=np.float64)

    dt = effective_dt(T_hor=T_hor, dt_ratio=dt_ratio, dt_abs_max=dt_abs_max)

    for i, (s, dx0, lam0, vl) in enumerate(X):
        remaining = max(T_hor - float(s), 0.0)

        if remaining <= 0.0 or dx0 <= 0.0:
            out[i] = 0.0
            continue

        elapsed = 0.0
        dx, lam, vl_now = float(dx0), float(lam0), float(vl)
        while elapsed < remaining - 1e-12:
            h = min(dt, remaining - elapsed)
            dx_prev = dx

            def rhs(t_abs, x, l, v):
                a_raw = float(leader_acceleration(t_abs))
                a = 0.0 if (v <= 0.0 and a_raw < 0.0) or (v >= VL_MAX and a_raw > 0.0) else a_raw
                v_follower = v - l
                return l, a - alpha * (optimal_velocity(x) - v_follower), a

            k1x, k1l, k1v = rhs(float(s) + elapsed, dx, lam, vl_now)
            k2x, k2l, k2v = rhs(float(s) + elapsed + 0.5*h, dx + 0.5*h*k1x, lam + 0.5*h*k1l, vl_now + 0.5*h*k1v)
            k3x, k3l, k3v = rhs(float(s) + elapsed + 0.5*h, dx + 0.5*h*k2x, lam + 0.5*h*k2l, vl_now + 0.5*h*k2v)
            k4x, k4l, k4v = rhs(float(s) + elapsed + h, dx + h*k3x, lam + h*k3l, vl_now + h*k3v)
            dx += h * (k1x + 2.0*k2x + 2.0*k3x + k4x) / 6.0
            lam += h * (k1l + 2.0*k2l + 2.0*k3l + k4l) / 6.0
            vl_now = np.clip(vl_now + h * (k1v + 2.0*k2v + 2.0*k3v + k4v) / 6.0, 0.0, VL_MAX)

            if dx <= 0.0:
                denom = max(dx_prev - dx, 1e-12)
                frac = np.clip(dx_prev / denom, 0.0, 1.0)
                out[i] = elapsed + h * frac
                break
            elapsed += h
        else:
            out[i] = remaining

    return out.astype(np.float64)


                                                              
                 
                                                              
def build_axis(lo, hi, step):
    """
    Robust axis builder that includes hi exactly.
    """
    lo = float(lo)
    hi = float(hi)
    step = float(step)

    if hi < lo:
        raise ValueError("hi must be >= lo")
    if step <= 0:
        raise ValueError("step must be > 0")

    vals = [lo]
    x = lo
    while x + step < hi - 1e-12:
        x = x + step
        vals.append(x)

    if hi - vals[-1] > 1e-12:
        vals.append(hi)
    else:
        vals[-1] = hi

    return np.asarray(vals, dtype=np.float64)


def centers_to_edges(vals):
    vals = np.asarray(vals, dtype=np.float64)
    if len(vals) == 1:
        h = 0.5
        return np.array([vals[0] - h, vals[0] + h], dtype=np.float64)

    mids = 0.5 * (vals[:-1] + vals[1:])
    left = vals[0] - 0.5 * (vals[1] - vals[0])
    right = vals[-1] + 0.5 * (vals[-1] - vals[-2])
    return np.concatenate([[left], mids, [right]])


def regression_metrics(y_true, y_pred):
    y_true = np.asarray(y_true, dtype=np.float64).ravel()
    y_pred = np.asarray(y_pred, dtype=np.float64).ravel()

    mae = float(np.mean(np.abs(y_true - y_pred)))
    mse = float(np.mean((y_true - y_pred) ** 2))
    rmse = float(np.sqrt(mse))
    ss_res = float(np.sum((y_true - y_pred) ** 2))
    ss_tot = float(np.sum((y_true - np.mean(y_true)) ** 2))
    r2 = 1.0 - ss_res / max(ss_tot, 1e-12)

    return {
        "mae": mae,
        "mse": mse,
        "rmse": rmse,
        "r2": float(r2),
    }


def assert_feasible_state_array(X, tol=1e-6):
    X = np.asarray(X, dtype=np.float64)
    s = X[:, 0]
    dx = X[:, 1]
    lam = X[:, 2]
    vl = X[:, 3]

    if np.any(s < -tol):
        raise ValueError("Found negative s.")
    if np.any(dx < XI_MIN - tol) or np.any(dx > XI_MAX + tol):
        raise ValueError("Found spacing outside admissible domain.")
    if np.any(lam < LAM_MIN - tol) or np.any(lam > LAM_MAX + tol):
        raise ValueError("Found relative velocity outside admissible domain.")
    if np.any(vl < VL_MIN - tol) or np.any(vl > VL_MAX + tol):
        raise ValueError("Found leading velocity outside admissible domain.")

    feasible_hi = np.maximum(0.0, V_MAX + lam)
    bad = (vl - feasible_hi) > tol
    if np.any(bad):
        idx = np.where(bad)[0][:10]
        lines = ["Found infeasible (λ, v_l) pairs where v_l > V_MAX + λ."]
        for i in idx:
            lines.append(
                f"idx={i}, lam={lam[i]:.12f}, vl={vl[i]:.12f}, "
                f"V_MAX+lam={feasible_hi[i]:.12f}, excess={vl[i]-feasible_hi[i]:.3e}"
            )
        raise ValueError("\n".join(lines))

    return True


                                                              
                                           
                                                
                                                              
def build_all_admissible_states_fixed_s(
    s_fixed,
    T_hor=1.0,
    dx_step=0.02,
    lam_step=0.02,
    vl_step=0.02,
):
    if s_fixed < 0.0 or s_fixed > T_hor:
        raise ValueError(f"s_fixed must be in [0, {T_hor}]")

    dx_vals = build_axis(XI_MIN, XI_MAX, dx_step)
    lam_vals = build_axis(LAM_MIN, LAM_MAX, lam_step)

    all_blocks = []
    dx_idx_all = []
    lam_idx_all = []
    pair_counts = np.zeros((len(lam_vals), len(dx_vals)), dtype=int)

    for li, lam in enumerate(lam_vals):
        vl_hi = max(0.0, float(V_MAX + lam))

        if vl_hi <= 1e-12:
            vl_vals = np.array([0.0], dtype=np.float64)
        else:
            vl_vals = build_axis(0.0, vl_hi, vl_step)
            vl_vals = np.clip(vl_vals, 0.0, vl_hi)
            vl_vals[-1] = vl_hi

        for di, dx in enumerate(dx_vals):
            n_vl = len(vl_vals)
            pair_counts[li, di] = n_vl

            block = np.column_stack([
                np.full(n_vl, s_fixed, dtype=np.float64),
                np.full(n_vl, dx, dtype=np.float64),
                np.full(n_vl, lam, dtype=np.float64),
                vl_vals.copy(),
            ])

            all_blocks.append(block)
            dx_idx_all.append(np.full(n_vl, di, dtype=np.int32))
            lam_idx_all.append(np.full(n_vl, li, dtype=np.int32))

    X64 = np.vstack(all_blocks)
    dx_idx = np.concatenate(dx_idx_all)
    lam_idx = np.concatenate(lam_idx_all)

                                                 
    assert_feasible_state_array(X64, tol=1e-6)

                                
    X32 = X64.astype(np.float32)

    return X32, X64, dx_vals, lam_vals, dx_idx, lam_idx, pair_counts


                                                              
                                           
                                                              
def aggregate_over_vl_mean(dx_vals, lam_vals, dx_idx, lam_idx, y_gt, y_pred, abs_err):
    n_lam = len(lam_vals)
    n_dx = len(dx_vals)

    Z_gt_sum = np.zeros((n_lam, n_dx), dtype=np.float64)
    Z_pred_sum = np.zeros((n_lam, n_dx), dtype=np.float64)
    Z_err_sum = np.zeros((n_lam, n_dx), dtype=np.float64)
    Z_count = np.zeros((n_lam, n_dx), dtype=np.int64)

    np.add.at(Z_gt_sum, (lam_idx, dx_idx), y_gt)
    np.add.at(Z_pred_sum, (lam_idx, dx_idx), y_pred)
    np.add.at(Z_err_sum, (lam_idx, dx_idx), abs_err)
    np.add.at(Z_count, (lam_idx, dx_idx), 1)

    Z_gt = np.divide(Z_gt_sum, Z_count, out=np.full_like(Z_gt_sum, np.nan), where=Z_count > 0)
    Z_pred = np.divide(Z_pred_sum, Z_count, out=np.full_like(Z_pred_sum, np.nan), where=Z_count > 0)
    Z_err = np.divide(Z_err_sum, Z_count, out=np.full_like(Z_err_sum, np.nan), where=Z_count > 0)

    return {
        "Z_gt": Z_gt,
        "Z_pred": Z_pred,
        "Z_err": Z_err,
        "Z_count": Z_count.astype(np.float64),
        "dx_edges": centers_to_edges(dx_vals),
        "lam_edges": centers_to_edges(lam_vals),
    }


                                                              
             
                                                              
def plot_2d_admissible_sweep(
    agg_dict,
    s_fixed,
    T_hor,
    metrics,
    out_path,
    show_vl_count=True,
):
    remaining = max(T_hor - s_fixed, 0.0)

    ncols = 4 if show_vl_count else 3
    fig, axes = plt.subplots(1, ncols, figsize=(7 * ncols, 6), constrained_layout=True)

    if ncols == 3:
        axes_main = axes
    else:
        axes_main = axes[:3]

    panels = [
        (agg_dict["Z_gt"], "Ground Truth", "viridis", 0.0, remaining, "mean GT over feasible $v_\\ell$"),
        (agg_dict["Z_pred"], "Prediction", "viridis", 0.0, remaining, "mean prediction over feasible $v_\\ell$"),
        (agg_dict["Z_err"], "Absolute Error", "Reds", 0.0, np.nanmax(agg_dict["Z_err"]), "mean abs error over feasible $v_\\ell$"),
    ]

    for ax, (Z, title, cmap, vmin, vmax, cbar_label) in zip(axes_main, panels):
        pcm = ax.pcolormesh(
            agg_dict["dx_edges"],
            agg_dict["lam_edges"],
            Z,
            shading="auto",
            cmap=cmap,
            vmin=vmin,
            vmax=vmax if np.isfinite(vmax) and vmax > vmin else None,
        )
        ax.set_xlabel(r"Spacing $\Delta x$")
        ax.set_ylabel(r"Relative velocity $\lambda$")
        ax.set_title(title)
        ax.set_xlim(XI_MIN, XI_MAX)
        ax.set_ylim(LAM_MIN, LAM_MAX)
        cbar = fig.colorbar(pcm, ax=ax, pad=0.02)
        cbar.set_label(cbar_label)

    if show_vl_count:
        ax = axes[3]
        pcm = ax.pcolormesh(
            agg_dict["dx_edges"],
            agg_dict["lam_edges"],
            agg_dict["Z_count"],
            shading="auto",
            cmap="Blues",
        )
        ax.set_xlabel(r"Spacing $\Delta x$")
        ax.set_ylabel(r"Relative velocity $\lambda$")
        ax.set_title("Number of feasible $v_\\ell$")
        ax.set_xlim(XI_MIN, XI_MAX)
        ax.set_ylim(LAM_MIN, LAM_MAX)
        cbar = fig.colorbar(pcm, ax=ax, pad=0.02)
        cbar.set_label("count")

    fig.suptitle(
        f"Admissible-state sweep at s = {s_fixed:.3f}\n"
        f"For each $(\\Delta x, \\lambda)$, all feasible $v_\\ell \\in [0, V_{{max}}+\\lambda]$ are evaluated\n"
        f"Global raw-state metrics: MAE = {metrics['mae']:.6f}, "
        f"RMSE = {metrics['rmse']:.6f}, R² = {metrics['r2']:.6f}",
        fontsize=13,
    )

    fig.savefig(out_path, dpi=220, bbox_inches="tight")
               
    plt.close(fig)


                                                              
                     
                                                              
def final_evaluation_admissible_2d(
    model_path,
    s_fixed=0.25,
    T_hor=1.0,
    alpha=2.0,
    dt_ratio=0.001,
    dt_abs_max=None,
    dx_step=0.02,
    lam_step=0.02,
    vl_step=0.02,
    batch_size=8192,
    out_dir=None,
):
    if out_dir is None:
        out_dir = os.path.join(
            os.path.dirname(model_path),
            f"admissible_2d_eval_s{str(s_fixed).replace('.', 'p')}"
        )
    os.makedirs(out_dir, exist_ok=True)

    print(f"[INFO] Loading model:\n  {model_path}")
    value_net = keras.models.load_model(model_path, compile=False)

    print("[INFO] Building all admissible states ...")
    X32, X64, dx_vals, lam_vals, dx_idx, lam_idx, pair_counts = build_all_admissible_states_fixed_s(
        s_fixed=s_fixed,
        T_hor=T_hor,
        dx_step=dx_step,
        lam_step=lam_step,
        vl_step=vl_step,
    )
    print(f"[INFO] Total number of raw admissible states = {len(X32):,}")
    print(f"[INFO] Grid size in (Δx, λ) = {len(dx_vals)} x {len(lam_vals)}")

    print("[INFO] Predicting NN output ...")
    y_pred = value_net.predict(X32, batch_size=batch_size, verbose=1).ravel()

    print("[INFO] Computing OVM ground truth ...")
    y_gt = compute_ground_truth_ovm(
        X64,
        T_hor=T_hor,
        alpha=alpha,
        dt_ratio=dt_ratio,
        dt_abs_max=dt_abs_max,
    )

    abs_err = np.abs(y_pred - y_gt)
    signed_err = y_pred - y_gt
    metrics = regression_metrics(y_gt, y_pred)

    print("[INFO] Metrics on all raw admissible states:")
    print(json.dumps(metrics, indent=2))

    df_raw = pd.DataFrame({
        "s": X64[:, 0],
        "dx": X64[:, 1],
        "lam": X64[:, 2],
        "vl": X64[:, 3],
        "dx_idx": dx_idx,
        "lam_idx": lam_idx,
        "y_pred": y_pred,
        "y_gt": y_gt,
        "signed_err": signed_err,
        "abs_err": abs_err,
    })

    with open(os.path.join(out_dir, "raw_metrics.json"), "w") as f:
        json.dump(metrics, f, indent=2)

    try:
        raw_path = os.path.join(out_dir, "raw_admissible_results.parquet")
        df_raw.to_parquet(raw_path, index=False)
        print(f"[INFO] Saved raw results to: {raw_path}")
    except Exception:
        raw_path = os.path.join(out_dir, "raw_admissible_results.csv")
        df_raw.to_csv(raw_path, index=False)
        print(f"[INFO] Saved raw results to: {raw_path}")

    print("[INFO] Aggregating over feasible v_l by mean ...")
    agg_dict = aggregate_over_vl_mean(
        dx_vals=dx_vals,
        lam_vals=lam_vals,
        dx_idx=dx_idx,
        lam_idx=lam_idx,
        y_gt=y_gt,
        y_pred=y_pred,
        abs_err=abs_err,
    )

    fig_path = os.path.join(out_dir, "admissible_2d_plot_mean.png")
    plot_2d_admissible_sweep(
        agg_dict=agg_dict,
        s_fixed=s_fixed,
        T_hor=T_hor,
        metrics=metrics,
        out_path=fig_path,
        show_vl_count=True,
    )
    print(f"[INFO] Saved figure to: {fig_path}")

    return {
        "model": value_net,
        "X32": X32,
        "X64": X64,
        "df_raw": df_raw,
        "metrics": metrics,
        "out_dir": out_dir,
        "figure_path": fig_path,
        "pair_counts": pair_counts,
        "dx_vals": dx_vals,
        "lam_vals": lam_vals,
        "agg_dict": agg_dict,
    }


                                                              
        
                                                              
